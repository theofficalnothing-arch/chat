// Packs the files in public/ into src/assets.js so the server has no files to read at run time.
// Run this after you change anything in public/:   deno task build    (or:  node build.js)
const fs = globalThis.Deno ? null : await import('node:fs');
const read = (p) => (fs ? fs.readFileSync(p, 'utf8') : Deno.readTextFileSync(p));
const write = (p, t) => (fs ? fs.writeFileSync(p, t) : Deno.writeTextFileSync(p, t));
const out = '// Generated by build.js from public/. Do not edit by hand.\n' +
  'export const INDEX_HTML = ' + JSON.stringify(read('public/index.html')) + ';\n' +
  'export const APP_JS = ' + JSON.stringify(read('public/app.js')) + ';\n' +
  'export const STYLE_CSS = ' + JSON.stringify(read('public/style.css')) + ';\n';
write('src/assets.js', out);
console.log('Wrote src/assets.js');
